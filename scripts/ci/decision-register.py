#!/usr/bin/env python3
"""
Decision register generator for secure-docker-blueprint.

Reads `.ai/decisions.md` and writes the register at the top of that file from
the ID heading and the field lines each entry carries. The register is a
presentation of the entries, never a second owner: a wrong line is corrected in
the entry and the block regenerated, exactly as LIFECYCLE.md is regenerated from
its sources. The entries themselves — heading, reasoning, alternatives, history —
are never read for content and never changed by this script.

Shape of an entry:

  ## 2026-10-18 · The middleware model as cut: eight decisions (D1–D8)

  ### DEC-064

  - **Decision:** decided 2026-10-18 · supersedes DEC-062, DEC-061 · depends on DEC-060 · answers review D1–D8 · area: reverse-proxy
  - **Parts:** .1 threat and compression on the entrypoint · .2 four positions on every router · …
  - **Implementation:** implemented 2026-10-23 (#258) → core/traefik/ops/templates/dynamic/model.yml.tmpl, docs/standards/traefik-security.md
  - **Verification:** mechanical — scripts/ci/test_traefik_model.py · host — open → core/traefik/docs/middleware-model-migration.md §5
  - **Inputs:** docs/audits/traefik-architecture-review-2026-10-17.md §9

Three axes are kept apart on purpose. A decision can be decided and not
implemented; implemented and never verified on a host. Each axis is one field
line, and the first word of each token is the state:

  Decision        decided <date> · superseded <date> by <target> · open since <date>
                  · direction · withdrawn <date>
                  then any of: supersedes <targets> · refines <targets> ·
                  depends on <targets> · answers <text> · rejects <text> ·
                  area: <area>  (the area is required)
  Implementation  implemented · partial · not started · contradicted · n/a
  Verification    mechanical · host · review · open · n/a   (several tokens allowed)

Tokens are separated by ` · `. A token may begin with a part suffix (`.1`, `.b`)
when the entry holds more than one decision; the parts are named in `Parts`. A
remark in parentheses after the state is free text. A relation target is a
`DEC-nnn` or `DEC-nnn.p` id, or `[no entry: …]` where the superseding decision
has no entry yet. Inverse relations (superseded by, refined by, needed by) are
derived and never written.

The ID heading `### DEC-nnn` is the stable anchor (`#dec-nnn`): the title may be
reworded, the id never changes and is never reused. Numbers are allocated once,
in the order decisions are recorded.

Consistency rules (--check):

FAIL:
  stale-register     the block between the markers differs from what the entries produce
  bad-id             an ID heading that is not `### DEC-nnn`
  duplicate-id       the same id under two headings
  missing-field      an entry with an ID heading lacks Decision, Implementation or Verification
  unknown-state      a field token whose first word is outside the vocabulary above
  unknown-token      a Decision token that is neither a state, a relation nor the area
  missing-area       no `area:` token in Decision
  unknown-area       an area outside AREAS
  bad-part           a part suffix used in a field line and not named in Parts
  dangling-relation  a relation names a DEC id no entry carries (strict mode)

WARN:
  unclassified       an entry without an ID heading — reported, listed under
                     "Not yet classified", and nothing is said about its state.
                     A warning while TRANSITION is "warn"; a failure once it is
                     "fail", which is the state after every entry carries lines.
  dangling-relation  the same as above while TRANSITION is "warn": the target may
                     be an entry that has no id yet
  no-entry-target    a relation written as `[no entry: …]` — the gap stays
                     visible in the chain until the entry is written
  open-ageing        an `open since` older than 90 days

Usage:
  python3 scripts/ci/decision-register.py            # report to stdout
  python3 scripts/ci/decision-register.py --write    # regenerate the block
  python3 scripts/ci/decision-register.py --check [github-summary-path]
  python3 scripts/ci/decision-register.py --compact  # drop the relation line under By area

--check exits 1 on FAIL only. Every mode exits 2 when the file is not found.
"""

from __future__ import annotations

import re
import sys
from datetime import date
from pathlib import Path

SOURCE = Path(".ai/decisions.md")

# Transition: "warn" while entries are being classified, "fail" afterwards.
TRANSITION = "warn"

START = ("<!-- register:start — generated by scripts/ci/decision-register.py "
         "from the ID headings and field lines below; edit the entries, never "
         "this block -->")
END = "<!-- register:end -->"

# Areas follow docs/architecture.md where it has a part for them; the last four
# are process areas the architecture does not describe.
AREAS = {
    "architecture": "Architecture and layout",
    "reverse-proxy": "Reverse proxy",
    "threat-detection": "Threat detection and remediation",
    "identity": "Identity and access",
    "network": "Network",
    "secrets": "Secrets",
    "hardening": "Container hardening and limits",
    "host": "Host",
    "backup": "Backup",
    "updates": "Updates and image provenance",
    "lifecycle": "Lifecycle and status",
    "catalogue": "Catalogue and scope",
    "release": "Release process",
    "governance": "Documentation and governance",
    "site": "Site and public content",
}

DECISION_STATES = ("decided", "superseded", "open since", "direction", "withdrawn")
IMPLEMENTATION_STATES = ("implemented", "partial", "not started", "contradicted", "n/a")
VERIFICATION_STATES = ("mechanical", "host", "review", "open", "n/a")
RELATIONS = ("supersedes", "refines", "depends on", "answers", "rejects")
INVERSE = {"supersedes": "superseded by", "refines": "refined by", "depends on": "needed by"}

WARN_RULES = {"no-entry-target", "open-ageing"}
TRANSITION_RULES = {"unclassified", "dangling-relation"}
OPEN_AGEING_DAYS = 90


def level(rule: str) -> str:
    """WARN or FAIL for a rule, honouring the transition switch."""
    if rule in WARN_RULES:
        return "WARN"
    if rule in TRANSITION_RULES:
        return "WARN" if TRANSITION == "warn" else "FAIL"
    return "FAIL"

HEADING = re.compile(r"^## (.+?)\s*$")
ID_HEADING = re.compile(r"^### (\S+)\s*$")
ID = re.compile(r"^DEC-(\d{3})$")
FIELD = re.compile(r"^- \*\*(Decision|Parts|Implementation|Verification|Inputs):\*\*\s*(.*)$")
ENTRY_DATE = re.compile(r"^(\d{4}-\d{2}(?:-\d{2})?)\s*·\s*(.*)$")
PART_PREFIX = re.compile(r"^\.(\w+)\s+(.*)$")
TARGET = re.compile(r"DEC-\d{3}(?:\.\w+)?")
NO_ENTRY = re.compile(r"\[no entry: ([^\]]+)\]")
DATE = re.compile(r"\d{4}-\d{2}(?:-\d{2})?")


def read(path: Path) -> str:
    if not path.exists():
        return ""
    return path.read_text(encoding="utf-8", errors="replace")


def split_tokens(value: str) -> list[str]:
    """Split on ` · ` outside parentheses and brackets."""
    tokens, depth, current = [], 0, []
    i = 0
    while i < len(value):
        ch = value[i]
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth = max(0, depth - 1)
        if depth == 0 and value.startswith(" · ", i):
            tokens.append("".join(current).strip())
            current = []
            i += 3
            continue
        current.append(ch)
        i += 1
    if "".join(current).strip():
        tokens.append("".join(current).strip())
    return tokens


def leading_state(text: str, states: tuple[str, ...]) -> str | None:
    """The state a token starts with — the longest match, so `open since` wins over `open`."""
    for state in sorted(states, key=len, reverse=True):
        if text == state or text.startswith((state + " ", state + ",")):
            return state
    return None


def strip_part(token: str) -> tuple[str | None, str]:
    m = PART_PREFIX.match(token)
    return (m.group(1), m.group(2)) if m else (None, token)


def targets_in(body: str) -> list[str]:
    """Every relation target in a token body: `DEC-nnn[.p]` ids and `[no entry: …]` gaps."""
    return TARGET.findall(body) + [f"[no entry: {t}]" for t in NO_ENTRY.findall(body)]


# ── parsing ──────────────────────────────────────────────────────────────────


def parse(text: str) -> tuple[list[dict], list[dict], list[dict]]:
    """Return (entries with an id, entries without, problems).

    Each classified entry: id, title, date, fields, parts, states, relations.
    The block between the markers is skipped so the register never reads itself.
    """
    entries: list[dict] = []
    unclassified: list[dict] = []
    problems: list[dict] = []

    lines = text.splitlines()
    in_block = False
    in_fence = False
    i = 0
    current: dict | None = None
    while i < len(lines):
        line = lines[i]
        if line.startswith(START):
            in_block = True
        elif line.strip() == END:
            in_block = False
            i += 1
            continue
        if in_block:
            i += 1
            continue
        if line.startswith("```"):
            in_fence = not in_fence
        if in_fence:
            i += 1
            continue

        h = HEADING.match(line)
        if h:
            heading = h.group(1)
            m = ENTRY_DATE.match(heading)
            current = {
                "heading": heading,
                "date": m.group(1) if m else "",
                "title": m.group(2) if m else heading,
                "id": None,
                "fields": {},
            }
            # the ID heading is the next non-blank line, if it is one
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            idh = ID_HEADING.match(lines[j]) if j < len(lines) else None
            if idh:
                raw = idh.group(1)
                if not ID.match(raw):
                    problems.append({"rule": "bad-id", "where": heading,
                                     "detail": f"`### {raw}` is not `### DEC-nnn`"})
                current["id"] = raw
                j += 1
                while j < len(lines) and not lines[j].strip():
                    j += 1
                while j < len(lines):
                    f = FIELD.match(lines[j])
                    if not f:
                        break
                    current["fields"][f.group(1)] = f.group(2).strip()
                    j += 1
                entries.append(current)
                i = j
                continue
            unclassified.append(current)
        i += 1

    seen: dict[str, str] = {}
    for e in entries:
        if e["id"] in seen:
            problems.append({"rule": "duplicate-id", "where": e["id"],
                             "detail": f"also used by `{seen[e['id']]}`"})
        seen[e["id"]] = e["heading"]
        interpret(e, problems)

    by_id = {e["id"]: e for e in entries}
    for e in entries:
        for rel in e["relations"]:
            if rel.get("free"):
                continue                      # `answers`/`rejects` name a recommendation, not an id
            target = rel["target"]
            if target.startswith("[no entry:"):
                problems.append({"rule": "no-entry-target", "where": e["id"],
                                 "detail": f"{rel['kind']} {target}"})
                continue
            base, _, part = target.partition(".")
            if base not in by_id:
                problems.append({"rule": "dangling-relation", "where": e["id"],
                                 "detail": f"{rel['kind']} {target} — no entry carries that id"
                                 + (" yet" if TRANSITION == "warn" else "")})
            elif part and part not in by_id[base]["parts"]:
                problems.append({"rule": "bad-part", "where": e["id"],
                                 "detail": f"{rel['kind']} {target} — `{base}` names no part `.{part}`"})

    for u in unclassified:
        problems.append({"rule": "unclassified", "where": u["heading"],
                         "detail": "no `### DEC-nnn` heading and no field lines"})

    return entries, unclassified, problems


def interpret(e: dict, problems: list[dict]) -> None:
    """Fill states, parts and relations from the field lines; record problems."""
    fields = e["fields"]
    e["parts"] = {}
    e["relations"] = []
    e["area"] = None
    e["states"] = {"Decision": {}, "Implementation": {}, "Verification": {}}
    e["tokens"] = {"Decision": [], "Implementation": [], "Verification": []}

    for name in ("Decision", "Implementation", "Verification"):
        if name not in fields:
            problems.append({"rule": "missing-field", "where": e["id"],
                             "detail": f"no `- **{name}:**` line"})

    if "Parts" in fields:
        for token in split_tokens(fields["Parts"]):
            part, rest = strip_part(token)
            if part:
                e["parts"][part] = rest

    vocab = {"Decision": DECISION_STATES, "Implementation": IMPLEMENTATION_STATES,
             "Verification": VERIFICATION_STATES}
    for name, states in vocab.items():
        if name not in fields:
            continue
        for token in split_tokens(fields[name]):
            part, rest = strip_part(token)
            if part and part not in e["parts"]:
                problems.append({"rule": "bad-part", "where": e["id"],
                                 "detail": f"{name}: `.{part}` is not named in Parts"})
            state = leading_state(rest, states)
            if state:
                key = part or "_"
                e["states"][name].setdefault(key, state)
                e["tokens"][name].append((part, rest))
                continue
            if name == "Decision":
                if rest.startswith("area:"):
                    area = rest[len("area:"):].strip()
                    e["area"] = area
                    if area not in AREAS:
                        problems.append({"rule": "unknown-area", "where": e["id"],
                                         "detail": f"`{area}` is not one of {', '.join(AREAS)}"})
                    continue
                rel = leading_state(rest, RELATIONS)
                if rel:
                    body = rest[len(rel):].strip()
                    if rel in ("answers", "rejects"):
                        e["relations"].append({"kind": rel, "target": body, "free": True})
                    else:
                        targets = targets_in(body)
                        for t in targets:
                            e["relations"].append({"kind": rel, "target": t, "free": False})
                        if not targets:
                            problems.append({"rule": "unknown-token", "where": e["id"],
                                             "detail": f"`{rel}` names no DEC id"})
                    continue
                problems.append({"rule": "unknown-token", "where": e["id"],
                                 "detail": f"Decision token `{token}` is neither a state, a relation nor the area"})
            else:
                problems.append({"rule": "unknown-state", "where": e["id"],
                                 "detail": f"{name} token `{token}` starts with no state of {', '.join(states)}"})

    if "Decision" in fields:
        if not e["states"]["Decision"]:
            problems.append({"rule": "unknown-state", "where": e["id"],
                             "detail": "Decision names no state"})
        if e["area"] is None:
            problems.append({"rule": "missing-area", "where": e["id"],
                             "detail": "Decision carries no `area:` token"})
        # superseded <date> by <target> — the target is a relation too
        for part, rest in e["tokens"]["Decision"]:
            if rest.startswith("superseded"):
                for t in targets_in(rest.partition(" by ")[2]):
                    e["relations"].append({"kind": "superseded by", "target": t, "free": False})
            if rest.startswith("open since"):
                m = DATE.search(rest)
                if m and len(m.group(0)) == 10:
                    opened = date.fromisoformat(m.group(0))
                    if (date.today() - opened).days > OPEN_AGEING_DAYS:
                        problems.append({"rule": "open-ageing", "where": e["id"],
                                         "detail": f"open since {m.group(0)}"})


# ── derived views ────────────────────────────────────────────────────────────


def state_of(e: dict, axis: str, part: str | None = None) -> str:
    """The unit's state: the part's own where it has one, else the entry's."""
    states = e["states"][axis]
    if part is not None and part in states:
        return states[part]
    return states.get("_", next(iter(states.values()), "—"))


def entry_state(e: dict, axis: str) -> str:
    return state_of(e, axis)


def units(e: dict, axis: str) -> list[tuple[str | None, str]]:
    """(part or None, state) — one per part that speaks for itself on this axis,
    else the entry once. A part that says nothing inherits the entry and is not
    listed again: eight parts with one shared verification are one line."""
    own = {p for p, _ in e["tokens"][axis] if p}
    parts = [p for p in e["parts"] if p in own]
    out = [(p, e["states"][axis][p]) for p in parts]
    if not parts or "_" in e["states"][axis]:
        out.insert(0, (None, entry_state(e, axis)))
    return out


def label_of(e: dict, part: str | None) -> str:
    return f"{e['id']}.{part}" if part else e["id"]


def own_tokens(e: dict, axis: str, part: str | None) -> str:
    """The tokens that speak for this unit: the part's own, or the entry's for None."""
    return " · ".join(r for p, r in e["tokens"][axis] if p == part)


def has_open_verification(e: dict, part: str | None) -> bool:
    return any(p == part and r.startswith("open") for p, r in e["tokens"]["Verification"])


def sort_key(e: dict) -> tuple[str, str]:
    d = e["date"] or "0000-00"
    return (d if len(d) == 10 else d + "-00", e["id"])


def link(e: dict) -> str:
    return f"[{e['title']}](#{e['id'].lower()})"


def base_id(node: str) -> str:
    return node if node.startswith("[no entry:") else node.split(".", 1)[0]


def chains(entries: list[dict]) -> list[list[str]]:
    """One line per chain of `supersedes`, oldest first, the head in bold.

    Edges are kept per decision, not per part: a decision superseded by
    `DEC-064.3` belongs to DEC-064's chain. Where a head replaced several
    predecessors they are listed in date order before it.
    """
    by_id = {e["id"]: e for e in entries}
    edges: dict[str, set[str]] = {}
    superseded: set[str] = set()
    for e in entries:
        for rel in e["relations"]:
            if rel["kind"] == "supersedes":
                edges.setdefault(e["id"], set()).add(base_id(rel["target"]))
                superseded.add(base_id(rel["target"]))
            elif rel["kind"] == "superseded by":
                edges.setdefault(base_id(rel["target"]), set()).add(e["id"])
                superseded.add(e["id"])

    def label(node: str) -> str:
        if node in by_id:
            return f"{node} {by_id[node]['title']} ({by_id[node]['date']})"
        return node

    def node_key(node: str) -> tuple[str, str]:
        return sort_key(by_id[node]) if node in by_id else ("9999-99-99", node)

    out: list[list[str]] = []
    for head in sorted((k for k in edges if k not in superseded), key=node_key):
        seen: set[str] = set()
        frontier = [head]
        while frontier:
            node = frontier.pop()
            for pred in edges.get(node, ()):
                if pred not in seen:
                    seen.add(pred)
                    frontier.append(pred)
        preds = sorted(seen, key=node_key)
        out.append([label(p) for p in preds] + [f"**{label(head)}**"])
    return out


def render(entries: list[dict], unclassified: list[dict], compact: bool = False) -> str:
    entries = sorted(entries, key=sort_key)
    n = len(entries)
    counts: dict[str, int] = {}
    for e in entries:
        for _part, state in units(e, "Decision"):
            counts[state] = counts.get(state, 0) + 1
    impl: dict[str, int] = {}
    for e in entries:
        for _part, state in units(e, "Implementation"):
            impl[state] = impl.get(state, 0) + 1

    def unit_line(e: dict, part: str | None, extra: str) -> str:
        return f"- **{label_of(e, part)}** {link(e)} · {extra}"

    needs, not_impl, unverified, contradicted = [], [], [], []
    for e in entries:
        for part, d_state in units(e, "Decision"):
            if d_state in ("open since", "direction"):
                needs.append(unit_line(e, part, own_tokens(e, "Decision", part)))
        for part, i_state in units(e, "Implementation"):
            if state_of(e, "Decision", part) == "decided" and i_state == "not started":
                not_impl.append(unit_line(e, part, own_tokens(e, "Decision", part)
                                          + " · " + own_tokens(e, "Implementation", part)))
            if i_state == "contradicted":
                contradicted.append(unit_line(e, part, own_tokens(e, "Implementation", part)))
        # a verification gap is listed where the `open` token stands: once for the
        # entry, and separately for a part that names its own
        for part, _state in units(e, "Verification"):
            if state_of(e, "Implementation", part) in ("implemented", "partial") \
                    and has_open_verification(e, part):
                unverified.append(unit_line(e, part, own_tokens(e, "Verification", part)))

    out = [START, "## Register", ""]
    order_d = ("decided", "superseded", "open since", "direction", "withdrawn")
    order_i = ("implemented", "partial", "not started", "contradicted", "n/a")
    tally = " · ".join(f"{k} {counts[k]}" for k in order_d if counts.get(k))
    itally = " · ".join(f"{k} {impl[k]}" for k in order_i if impl.get(k))
    decisions = sum(counts.values())
    out.append(f"{n} classified entr{'ies' if n != 1 else 'y'}, {decisions} decision{'s' if decisions != 1 else ''} "
               f"— {tally} — implementation: {itally} — implemented and not verified on a host: {len(unverified)}")
    if unclassified:
        out.append("")
        many = len(unclassified) != 1
        out.append(f"Transition: {len(unclassified)} entr{'ies' if many else 'y'} "
                   f"carr{'y' if many else 'ies'} no field lines yet and {'are' if many else 'is'} "
                   "listed under *Not yet classified*; the register says nothing about "
                   f"{'their' if many else 'its'} state.")
    out.append("")

    for title, items in (("Needs the maintainer", needs),
                         ("Decided, not implemented", not_impl),
                         ("Implemented, not verified on a host", unverified),
                         ("Contradicted by the tree", contradicted)):
        out += [f"### {title}", ""]
        out += items or ["- none"]
        out.append("")

    # ── chains ──
    out += ["### Chains — what replaced what", ""]
    ch = chains(entries)
    out += [f"- {' → '.join(seq)}" for seq in ch] or ["- none"]
    out.append("")

    # ── by area ──
    out += ["### By area", ""]
    by_id = {e["id"]: e for e in entries}
    inverse: dict[str, list[str]] = {}
    for e in entries:
        for rel in e["relations"]:
            if rel["kind"] in INVERSE and not rel["target"].startswith("[no entry:"):
                base = base_id(rel["target"])
                # an entry whose own Decision already says `superseded by X`
                # does not get the derived copy of the same fact
                if rel["kind"] == "supersedes" and base in by_id and any(
                        r["kind"] == "superseded by" and base_id(r["target"]) == e["id"]
                        for r in by_id[base]["relations"]):
                    continue
                inverse.setdefault(base, []).append(f"{INVERSE[rel['kind']]} {e['id']}")
    for area, area_title in AREAS.items():
        group = [e for e in entries if e["area"] == area]
        if not group:
            continue
        out += [f"#### {area_title}", ""]
        for e in group:
            f = e["fields"]
            d_text = " · ".join(t for t in split_tokens(f.get("Decision", ""))
                                if not t.startswith("area:") and not leading_state(t, RELATIONS))
            out.append(f"- **{e['id']}** {link(e)} · {e['date']} · {d_text} · "
                       f"{f.get('Implementation', '')} · {f.get('Verification', '')}")
            if not compact:
                rel_bits = []
                grouped: dict[str, list[str]] = {}
                for rel in e["relations"]:
                    if rel["kind"] == "superseded by":
                        continue        # already in the Decision text
                    grouped.setdefault(rel["kind"], []).append(rel["target"])
                for kind in RELATIONS:
                    if kind in grouped:
                        rel_bits.append(f"{kind} {', '.join(grouped[kind])}")
                rel_bits += inverse.get(e["id"], [])
                if e["parts"]:
                    rel_bits.append("parts " + " · ".join(f".{p} {t}" for p, t in e["parts"].items()))
                if f.get("Inputs"):
                    rel_bits.append("inputs: " + f["Inputs"])
                if rel_bits:
                    out.append("  ↳ " + " · ".join(rel_bits))
        out.append("")

    if unclassified:
        # Listed by title, not linked: the title anchor is what the id heading
        # replaces, and two anchor rules disagree on headings with an underscore.
        out += ["### Not yet classified", ""]
        for u in sorted(unclassified, key=lambda u: (u["date"] or "", u["title"])):
            out.append(f"- {u['title']} — {u['date'] or 'undated'}")
        out.append("")

    out.append(END)
    return "\n".join(out)


# ── the file ─────────────────────────────────────────────────────────────────


def split_file(text: str) -> tuple[str, str | None, str]:
    """Return (before, block, after). `block` is None when no markers exist."""
    start = text.find(START)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        return text, None, ""
    end_len = len(END)
    return text[:start], text[start:end + end_len], text[end + end_len:]


def insert_point(text: str) -> int:
    """Where the block goes when there is none: before the first `---` that
    precedes the first entry heading."""
    first_entry = re.search(r"^## \d{4}-\d{2}", text, re.M)
    limit = first_entry.start() if first_entry else len(text)
    rule = text.rfind("\n---\n", 0, limit)
    return rule + 1 if rule != -1 else limit


def with_block(text: str, block: str) -> str:
    before, old, after = split_file(text)
    if old is not None:
        return before + block + after
    at = insert_point(text)
    return text[:at] + block + "\n\n" + text[at:]


def main() -> int:
    args = sys.argv[1:]
    mode = "report"
    compact = False
    if "--compact" in args:
        compact = True
        args.remove("--compact")
    if "--write" in args:
        mode = "write"
        args.remove("--write")
    elif "--check" in args:
        mode = "check"
        args.remove("--check")

    if not SOURCE.exists():
        print(f"error: {SOURCE} not found — run from the repository root", file=sys.stderr)
        return 2

    text = read(SOURCE)
    entries, unclassified, problems = parse(text)
    block = render(entries, unclassified, compact=compact)

    if mode == "write":
        SOURCE.write_text(with_block(text, block), encoding="utf-8")
        print(f"  ✅ {SOURCE} written — {len(entries)} classified, {len(unclassified)} not yet")
        return 0

    _before, old, _after = split_file(text)
    if old != block:
        problems.append({"rule": "stale-register", "where": str(SOURCE),
                         "detail": "the block differs from the entries — run --write"})

    fails = [p for p in problems if level(p["rule"]) == "FAIL"]
    warns = [p for p in problems if level(p["rule"]) == "WARN"]

    print()
    print("  Decision register")
    print()
    by_rule: dict[str, list[dict]] = {}
    for p in problems:
        by_rule.setdefault(p["rule"], []).append(p)
    for rule, items in sorted(by_rule.items(), key=lambda kv: -len(kv[1])):
        icon = "🟡" if level(rule) == "WARN" else "🔴"
        print(f"  {icon} {rule}  ({len(items)})")
        for p in items[:8]:
            print(f"       {p['where']}: {p['detail']}")
        if len(items) > 8:
            print(f"       … and {len(items) - 8} more")
        print()
    status = "❌" if fails else "✅"
    print(f"  {status} {len(entries)} classified  ·  {len(unclassified)} not yet  ·  "
          f"{len(fails)} failure(s)  ·  {len(warns)} warning(s)")
    print()

    if args:
        lines = [
            "## Decision register\n",
            f"{status} {len(entries)} classified, {len(unclassified)} not yet classified, "
            f"**{len(fails)} failure(s)**, {len(warns)} warning(s)\n",
        ]
        if problems:
            lines += ["| Level | Rule | Where | Detail |", "|---|---|---|---|"]
            for p in problems:
                icon = "🟡 WARN" if level(p["rule"]) == "WARN" else "🔴 FAIL"
                lines.append(f"| {icon} | `{p['rule']}` | `{p['where']}` | {p['detail']} |")
        Path(args[0]).write_text("\n".join(lines) + "\n", encoding="utf-8")

    return 1 if (mode == "check" and fails) else 0


if __name__ == "__main__":
    sys.exit(main())
